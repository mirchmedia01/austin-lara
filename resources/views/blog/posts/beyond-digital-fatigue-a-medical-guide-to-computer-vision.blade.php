<h2><strong>Understanding the Medical Side of Digital Eye Strain</strong></h2>
<p>CVS isn't just about tired eyes — it's a combination of ocular, neurological, and behavioral factors. Here's a warm, simple breakdown of what's actually happening.</p>
<h3><strong>1. Your Eyes Were Not Designed for Long-Term Near Work</strong></h3>
<p>Screens force your eyes to maintain focus at a single distance for hours. This strains the accommodative system, responsible for shifting focus between far and near.</p>
<p>When it overworks, symptoms appear:</p>
<ul>
    <li>Difficulty maintaining clear near vision</li>
    <li>Blurry distance vision after computer use</li>
    <li>Double vision during long work sessions</li>
    <li>Trouble concentrating during reading</li>
</ul>
<p>Think of it as your eye muscles getting stuck in "near mode."</p>
<h3><strong>2. Your Blink Rate Drops — Dramatically</strong></h3>
<p>Studies show that blinking decreases by up to 60% during screen use. This leads to:</p>
<ul>
    <li>Evaporative dry eye</li>
    <li>Burning or stinging sensations</li>
    <li>Redness</li>
    <li>Fluctuating vision</li>
</ul>
<p>CVS often overlaps with Meibomian Gland Dysfunction, a common condition triggered by reduced blinking.</p>
<h3><strong>3. The Body Responds Too — Not Just Your Eyes</strong></h3>
<p>Screens affect posture, and posture affects vision. Poor monitor ergonomics can cause:</p>
<ul>
    <li>Neck tension</li>
    <li>Shoulder pain</li>
    <li>Upper back strain</li>
</ul>
<p>This physical discomfort is considered part of the CVS diagnosis because the visual system and musculoskeletal system work together.</p>
<h3><strong>4. Light &amp; Glare Make Everything Harder</strong></h3>
<p>Blue light isn't "dangerous" — but it is visually uncomfortable, especially on older screens or poorly lit workspaces. Glare, reflections, and contrast issues all add strain.</p>
