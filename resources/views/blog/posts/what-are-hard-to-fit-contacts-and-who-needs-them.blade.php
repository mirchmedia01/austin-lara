<h2><strong>Types of Specialty Contact Lenses</strong></h2>

<p>At Austin Optics, specialty contact lenses in Forest Hills may include:</p>

<ul>
    <li><strong>Scleral lenses</strong>, which vault over the cornea and rest on the sclera, creating a liquid reservoir for comfort</li>
    <li><strong>Rigid Gas Permeable (RGP) lenses</strong> for sharper optics and durability</li>
